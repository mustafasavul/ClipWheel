export type I18nKey = keyof typeof translations.en;
export type Translator = (key: I18nKey) => string;

export function resolveLanguage(setting: LanguageSetting, systemLanguage = getSystemLanguage()): LanguageCode {
  if (setting === 'en' || setting === 'tr') return setting;
  return systemLanguage.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function getSystemLanguage(): string {
  if (typeof navigator === 'undefined') return 'en';
  return navigator.languages?.[0] ?? navigator.language ?? 'en';
}

export function getLanguageLocale(language: LanguageCode): string {
  return language === 'tr' ? 'tr-TR' : 'en-US';
}

export function createTranslator(language: LanguageCode): Translator {
  return (key) => translations[language][key] ?? translations.en[key] ?? key;
}
